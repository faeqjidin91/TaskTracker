#!/usr/bin/env bash
# Builds the TaskTracker API and Web Docker images.
#
#   ./scripts/docker-build.sh --up
#   ./scripts/docker-build.sh --framework net8.0 --tag net8 --no-cache
set -euo pipefail

framework=net10.0
tag=latest
no_cache=()
start=false

usage() {
    echo "Usage: $0 [--framework net10.0|net8.0] [--tag TAG] [--no-cache] [--up]"
}

while [ $# -gt 0 ]; do
    case "$1" in
        --framework) framework="${2:-}"; shift 2 ;;
        --tag) tag="${2:-}"; shift 2 ;;
        --no-cache) no_cache=(--no-cache); shift ;;
        --up) start=true; shift ;;
        -h|--help) usage; exit 0 ;;
        *) echo "Unknown option: $1"; usage; exit 2 ;;
    esac
done

case "$framework" in
    net10.0|net8.0) ;;
    *) echo "Framework must be net10.0 or net8.0."; exit 2 ;;
esac

if ! [[ "$tag" =~ ^[A-Za-z0-9_][A-Za-z0-9_.-]{0,127}$ ]]; then
    echo "Invalid image tag: $tag"
    exit 2
fi

cd "$(dirname "${BASH_SOURCE[0]}")/.."

env_value() {
    local value
    value=$(grep -E "^$1=" .env | head -n 1 | cut -d= -f2- | tr -d '\r' || true)
    echo "${value:-${2:-}}"
}

if [ ! -f .env ]; then
    cp .env.example .env
    echo "Created .env from .env.example. Set MSSQL_SA_PASSWORD in it, then run this script again."
    exit 1
fi

sa_password=$(env_value MSSQL_SA_PASSWORD)
if [ -z "$sa_password" ] || [ "$sa_password" = "change-me" ]; then
    echo "Set a strong MSSQL_SA_PASSWORD in .env, then run this script again."
    exit 1
fi

# The key stays in the git-ignored .env, and an existing key is never replaced.
if [ -z "$(env_value JWT_SIGNING_KEY)" ]; then
    key=$(openssl rand -base64 48 | tr -d '\r\n')
    if grep -qE '^JWT_SIGNING_KEY=' .env; then
        sed -i -E "s|^JWT_SIGNING_KEY=.*$|JWT_SIGNING_KEY=$key|" .env
    else
        [ -z "$(tail -c 1 .env)" ] || echo >> .env
        printf '\n# Generated by scripts/docker-build.\nJWT_SIGNING_KEY=%s\n' "$key" >> .env
    fi
    echo "Generated JWT_SIGNING_KEY in .env."
fi

export DOTNET_TFM="$framework"
export DOTNET_VERSION="${framework#net}"
export IMAGE_TAG="$tag"

echo "Building tasktracker-api:$tag and tasktracker-web:$tag for $framework..."
docker compose build ${no_cache[@]+"${no_cache[@]}"} api web

if [ "$start" = true ]; then
    docker compose up -d --wait
    echo
    echo "Web:     http://localhost:$(env_value WEB_PORT 8090)"
    echo "API:     http://localhost:$(env_value API_PORT 8091)"
    echo "Swagger: http://localhost:$(env_value API_PORT 8091)/swagger"
else
    echo "Images built. Start them with: docker compose up -d --wait"
fi
