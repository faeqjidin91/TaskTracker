<#
.SYNOPSIS
    Builds the TaskTracker API and Web Docker images.

.EXAMPLE
    .\scripts\docker-build.ps1 -Up

.EXAMPLE
    .\scripts\docker-build.ps1 -Framework net8.0 -Tag net8 -NoCache
#>
[CmdletBinding()]
param(
    # Defaults to DOTNET_TFM in .env, then net10.0.
    [ValidateSet('net10.0', 'net8.0')]
    [string]$Framework,

    # Defaults to IMAGE_TAG in .env, then latest.
    [ValidatePattern('^[A-Za-z0-9_][A-Za-z0-9_.-]{0,127}$')]
    [string]$Tag,

    # Rebuilds every layer.
    [switch]$NoCache,

    # Starts the full stack after building.
    [switch]$Up
)

$ErrorActionPreference = 'Stop'

function Invoke-Docker {
    & docker @args
    if ($LASTEXITCODE -ne 0) {
        throw "docker $($args -join ' ') failed with exit code $LASTEXITCODE."
    }
}

function Get-EnvValue([string[]]$Lines, [string]$Name, [string]$Default) {
    $line = $Lines | Where-Object { $_ -like "$Name=*" } | Select-Object -First 1
    if (-not $line) { return $Default }
    $value = ($line -split '=', 2)[1].Trim()
    if ($value) { return $value }
    return $Default
}

$root = Split-Path -Parent $PSScriptRoot
Push-Location $root
try {
    $envPath = Join-Path $root '.env'
    if (-not (Test-Path $envPath)) {
        Copy-Item (Join-Path $root '.env.example') $envPath
        Write-Host 'Created .env from .env.example. Set MSSQL_SA_PASSWORD in it, then run this script again.'
        exit 1
    }

    $lines = @(Get-Content $envPath)

    $targetFramework = if ($Framework) { $Framework } else { Get-EnvValue $lines 'DOTNET_TFM' 'net10.0' }
    if ($targetFramework -cnotin @('net10.0', 'net8.0')) {
        Write-Host 'DOTNET_TFM must be net10.0 or net8.0.'
        exit 2
    }

    $imageTag = if ($Tag) { $Tag } else { Get-EnvValue $lines 'IMAGE_TAG' 'latest' }
    if ($imageTag -cnotmatch '^[A-Za-z0-9_][A-Za-z0-9_.-]{0,127}$') {
        Write-Host "Invalid image tag: $imageTag"
        exit 2
    }

    $saPassword = Get-EnvValue $lines 'MSSQL_SA_PASSWORD' ''
    if (-not $saPassword -or $saPassword -eq 'change-me') {
        Write-Host 'Set a strong MSSQL_SA_PASSWORD in .env, then run this script again.'
        exit 1
    }

    # The key stays in the git-ignored .env, and an existing key is never replaced.
    if (-not (Get-EnvValue $lines 'JWT_SIGNING_KEY' '')) {
        $bytes = New-Object byte[] 48
        [Security.Cryptography.RandomNumberGenerator]::Create().GetBytes($bytes)
        $entry = 'JWT_SIGNING_KEY=' + [Convert]::ToBase64String($bytes)

        if ($lines | Where-Object { $_ -like 'JWT_SIGNING_KEY=*' }) {
            $lines = @($lines | ForEach-Object { if ($_ -like 'JWT_SIGNING_KEY=*') { $entry } else { $_ } })
        }
        else {
            $lines = @($lines) + '' + '# Generated by scripts/docker-build.' + $entry
        }

        [IO.File]::WriteAllLines($envPath, [string[]]$lines, (New-Object Text.UTF8Encoding $false))
        Write-Host 'Generated JWT_SIGNING_KEY in .env.'
    }

    $env:DOTNET_TFM = $targetFramework
    $env:IMAGE_TAG = $imageTag

    Write-Host "Building tasktracker-api:$imageTag and tasktracker-web:$imageTag for $targetFramework..."
    $buildArgs = @('compose', 'build')
    if ($NoCache) { $buildArgs += '--no-cache' }
    $buildArgs += @('api', 'web')
    Invoke-Docker @buildArgs

    if ($Up) {
        Invoke-Docker compose up -d --wait
        $webPort = Get-EnvValue $lines 'WEB_PORT' '8090'
        $apiPort = Get-EnvValue $lines 'API_PORT' '8091'
        Write-Host ''
        Write-Host "Web:     http://localhost:$webPort"
        Write-Host "API:     http://localhost:$apiPort"
        Write-Host "Swagger: http://localhost:$apiPort/swagger"
    }
    else {
        Write-Host 'Images built. Start them with: docker compose up -d --wait'
    }
}
finally {
    Pop-Location
}
